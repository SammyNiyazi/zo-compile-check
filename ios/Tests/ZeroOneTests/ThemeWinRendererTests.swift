    func testExactCurvedStarHasFourCanonicalCubicSegments() {
        var moves: [CGPoint] = [], ends: [CGPoint] = [], controls: [(CGPoint, CGPoint)] = []
        var closes = 0, unexpected = 0
        ThemeWinGeometry.sparklePath().forEach { element in
            switch element {
            case .move(let point): moves.append(point)
            case .curve(let end, let first, let second): ends.append(end); controls.append((first, second))
            case .closeSubpath: closes += 1
            default: unexpected += 1
            }
        }
        XCTAssertEqual(moves, [CGPoint(x: 0, y: -10)])
        XCTAssertEqual(ends, [CGPoint(x: 10, y: 0), CGPoint(x: 0, y: 10), CGPoint(x: -10, y: 0), CGPoint(x: 0, y: -10)])
        XCTAssertEqual(controls.count, 4)
        let expected: [(CGPoint, CGPoint)] = [
            (CGPoint(x: 1.2, y: -2.4), CGPoint(x: 2.4, y: -1.2)),
            (CGPoint(x: 2.4, y: 1.2), CGPoint(x: 1.2, y: 2.4)),
            (CGPoint(x: -1.2, y: 2.4), CGPoint(x: -2.4, y: 1.2)),
            (CGPoint(x: -2.4, y: -1.2), CGPoint(x: -1.2, y: -2.4))
        ]
        for (pair, fixture) in zip(controls, expected) {
            // Path keeps Float precision on iOS 26.
            for (actual, wanted) in [(pair.0, fixture.0), (pair.1, fixture.1)] {
                XCTAssertEqual(actual.x, wanted.x, accuracy: 0.0001); XCTAssertEqual(actual.y, wanted.y, accuracy: 0.0001)
            }
        }
        XCTAssertEqual(closes, 1)
        XCTAssertEqual(unexpected, 0)
    }

