    func testDeadlinesTierOriginAndFiniteElapsedAdmission() {
        let goal = ThemeWinTier.goal(origin: CGPoint(x: 80, y: 42))
        let cases: [(ZOTheme, Double)] = [(.core, 1.92), (.retro, 2.4), (.princess, 2.4), (.freak, 2.16)]
        for (theme, deadline) in cases {
            XCTAssertEqual(ThemeWinTimeline.cleanupDeadline(theme: theme, tier: .major, reduceMotion: false), deadline, accuracy: 0.000001)
            XCTAssertTrue(ThemeWinTimeline.isActive(theme: theme, tier: .major, elapsed: deadline - 0.001, reduceMotion: false))
            XCTAssertFalse(ThemeWinTimeline.isActive(theme: theme, tier: .major, elapsed: deadline + 0.001, reduceMotion: false))
            for elapsed in [Double.nan, .infinity, -.infinity, -0.01] {
                XCTAssertFalse(ThemeWinTimeline.isActive(theme: theme, tier: .major, elapsed: elapsed, reduceMotion: false))
            }
        }
        XCTAssertEqual(goal.duration, 1.2)
        XCTAssertEqual(ThemeWinTimeline.cleanupDeadline(theme: .core, tier: goal, reduceMotion: false), 1.32, accuracy: 0.000001)
        for theme in [ZOTheme.retro, .freak, .princess] {
            XCTAssertEqual(ThemeWinTimeline.cleanupDeadline(theme: theme, tier: goal, reduceMotion: true), 1.92)
        }
        XCTAssertFalse(ThemeWinTimeline.isActive(theme: .core, tier: goal, elapsed: 0, reduceMotion: true))
    }

